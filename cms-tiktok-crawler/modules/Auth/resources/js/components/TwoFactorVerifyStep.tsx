import React from 'react';
import { Flex, QRCode, Space, Typography } from 'antd';
import { SafetyCertificateFilled } from '@ant-design/icons';
import type { TwoFactorChallengeData } from '../Action/auth';
import OtpVerificationForm from './OtpVerificationForm';

const { Text, Paragraph } = Typography;

export interface TwoFactorVerifyStepProps {
	challenge: TwoFactorChallengeData;
	loading: boolean;
	error: string | null;
	onVerify: (otp: string) => void;
	onBack: () => void;
}

export default function TwoFactorVerifyStep({ challenge, loading, error, onVerify, onBack }: TwoFactorVerifyStepProps) {
	const header = (
		<div style={{ textAlign: 'center', marginBottom: 20 }}>
			{!challenge.enrolled && challenge.qr_code_url ? (
				<Space direction="vertical" size={10} style={{ width: '100%' }}>
					<Text strong style={{ fontSize: 14 }}>
						Step 1: Scan QR Code with Google Authenticator
					</Text>
					<Flex justify="center">
						<div
							style={{
								padding: 12,
								background: '#ffffff',
								borderRadius: 12,
								border: '1px solid #e2e8f0',
								boxShadow: '0 2px 8px rgba(0,0,0,0.05)',
							}}
						>
							<QRCode value={challenge.qr_code_url} size={150} bordered={false} />
						</div>
					</Flex>
					{challenge.secret_key && (
						<>
							<Text type="secondary" style={{ fontSize: 12 }}>
								Or enter secret key manually:
							</Text>
							<Paragraph copyable style={{ fontSize: 13, fontFamily: 'monospace', margin: 0 }}>
								{challenge.secret_key}
							</Paragraph>
						</>
					)}
				</Space>
			) : (
				<div style={{ padding: '8px 0' }}>
					<SafetyCertificateFilled style={{ fontSize: 48, color: '#EC008C', marginBottom: 8 }} />
					<Paragraph type="secondary" style={{ fontSize: 13, margin: 0 }}>
						Enter the 6-digit security code generated by your Google Authenticator app.
					</Paragraph>
				</div>
			)}
		</div>
	);

	return <OtpVerificationForm loading={loading} error={error} header={header} codeLabel="Verification Code (6 digits)" onVerify={onVerify} onBack={onBack} />;
}
